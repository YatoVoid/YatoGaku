export function getRadicals(character: string): KangxiRadical[] {
  const rads = KANJI_RADICALS[character] || [];
  const radicalMap = new Map(KANGXI_RADICALS.map(r => [r.character, r]));
  return rads.map(r => radicalMap.get(r)).filter((r): r is KangxiRadical => r !== undefined);
}

export function getKanjiByRadical(radical: string): string[] {
  return Object.entries(KANJI_RADICALS)
    .filter(([_, rads]) => rads.includes(radical))
    .map(([kanji]) => kanji);
}

/** Returns full KanjiItem objects for all kanji containing the given radical */
export function getKanjiItemsByRadical(radical: string): KanjiItem[] {
  const chars = getKanjiByRadical(radical);
  const map = getAllKanjiMap();
  return chars
    .map(c => map.get(c))
    .filter((item): item is KanjiItem => item !== undefined);
}
